const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const ts = require('typescript');
const source = path.join(__dirname, '../src/module/commissions/buyerCommissionFlow.ts');
const moduleExports = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync(source, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText, { exports: moduleExports, Date });
const { buyerCommissionFlow: flow, buyerMilestoneLabels: labels } = moduleExports;
const base = { id: 1, art_type: 'Digital', status: 'AWAITING_FUNDS', agreement_id: 1, fully_signed: true, funding_due_at: '2099-01-01T00:00:00Z', milestones: [] };
assert.equal(flow(base).action, 'fund');
assert.equal(flow(base).step, 2);
assert.equal(flow({ ...base, fully_signed: false }).action, 'agreement');
assert.equal(flow({ ...base, funding_pending: true }).action, 'verify');
assert.equal(flow({ ...base, funding_due_at: '2000-01-01T00:00:00Z' }).action, 'reload');
assert.equal(flow({ ...base, status: 'CANCELLED' }).action, 'none');
assert.equal(flow({ ...base, disputed: true }).action, 'help');
const funded = { ...base, status: 'STAGE_1', funded_at: '2026-11-04T00:00:00Z' };
assert.notEqual(flow(funded).action, 'fund');
assert.equal(flow(funded).step, 3);
assert.equal(labels(funded, { number: 1, status: 'PENDING', payout_status: 'NOT_REQUESTED' }).payout, 'Funds held');
assert.equal(labels(base, { number: 1, status: 'PENDING', payout_status: 'NOT_REQUESTED' }).payout, 'Not funded');
const approved = { number: 1, approved_at: '2026-11-04', status: 'APPROVED', payout_status: 'PROCESSING' };
assert.equal(labels(funded, approved).work, 'Approved');
assert.equal(labels(funded, approved).payout, 'Payout processing');
assert.equal(labels(funded, { ...approved, payout_status: 'SUCCEEDED' }).payout, 'Payout confirmed');
assert.equal(labels(funded, { number: 1, status: 'SUBMITTED', revision_used: true }).revision, 'Used · 1 of 1');
assert.equal(labels(funded, { number: 1, status: 'REVISION_REQUESTED', revision_used: true }).work, 'Waiting for artist’s revised submission');
const final = { id: 3, number: 3, label: 'Final deliverable', status: 'SUBMITTED', submissions: [{ id: 5 }] };
const physical = { ...funded, art_type: 'Physical', status: 'STAGE_3', milestones: [final] };
assert.equal(flow(physical).step, 4);
assert.match(flow(physical).title, /preview before delivery/);
assert.match(flow({ ...physical, milestones: [{ ...final, delivery_ready_at: '2026-11-04' }], delivery: { status: 'in_transit' } }).title, /prepared or delivered/);
assert.match(flow({ ...physical, delivery: { status: 'delivered', has_delivery_proof: true } }).title, /Confirm receipt/);
assert.match(flow({ ...physical, delivered_at: '2026-11-04' }).title, /Inspect the delivered artwork/);
assert.match(flow({ ...funded, status: 'STAGE_3', milestones: [final] }).description, /original file unlocks after final approval/);
assert.equal(flow({ ...physical, status: 'COMPLETE' }).step, 5);
assert.match(flow({ ...physical, status: 'COMPLETE' }).description, /Payout confirmation is shown separately/);
console.log('Buyer commission flow checks passed: signature and payment gates, payout labels, revision allowance, digital review, physical delivery, completion.');
